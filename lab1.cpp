#include <iostream> // Підключаємо бібліотеку для введення та виведення даних

int main() { 
  // Змінна для збереження температури у градусах Цельсія (TC)
  double TC;
 // Запитуємо у користувача температуру в градусах Цельсія
 std::cout << "Введіть температуру в Цельсіях (TC): ";
 std::cin >> TC;

 // Переводимо Цельсії у Фаренгейти за формулою: TF = TC * 9/5 + 32
 // Використовуємо 9.0 / 5.0 для точного ділення з дробовою частиною
 double TF = TC * 9.0 / 5.0 + 32;

 // Виводимо результат
 std::cout << "Температура у Фаренгейтах (TF): " << TF << std::endl;

 return 0; // Успішне завершення програми
}


