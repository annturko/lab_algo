#include <iostream> // Підключаємо бібліотеку для введення та виведення даних  
int main() {  
  double a, b, c; // Викор. double, щоб працювало з дробовими числами  
 
  // Введення трьох чисел  
  std::cout << "Введіть a: ";  
  std::cin >> a;  
  std::cout << "Введіть b: ";  
  std::cin >> b;  
  std::cout << "Введіть c: ";  
  std::cin >> c;  
 
  // Обчислення суми квадратів  
  double result = a * a + b * b + c * c;   
 
  // Вивід результату  
  std::cout << "Сума квадратів: " << result << std::endl;  
  return 0; 
}


