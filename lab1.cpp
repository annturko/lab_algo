#include <iostream> // Підключаемо бібліотеку для введення та виведення данних

int main() {
  // Оголошуемо змінні для реберпаралелопіпеда (a, b, c)

 // Запитуємо у користувача значення ребер
 std::cout << "Введіть довжини ребер a, b, c: ";
 std::cin >> a >> b >> c;

 // Обчислюємо об'єм: V = a * b * c
 double V = a * b * c;

 // Обчислюємо площу поверхні: S = 2 * (a*b + b*c + a*c)
 double S = 2 * (a * b + b * c + a * c);

 // Виводимо результати на екран
 std::cout << "Об'єм V = " << V << std::endl;
 std::cout << "Площа поверхні S = " << S << std::endl;

 return 0; // Успішне завершення програми
}


